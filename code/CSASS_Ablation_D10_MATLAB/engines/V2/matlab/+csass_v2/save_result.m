function save_result(result,directory)
if ~isfolder(directory), mkdir(directory); end
assert(~isfile(fullfile(directory,'run.mat')), ...
    'Output already contains run.mat; use a new directory to preserve evidence.');
save(fullfile(directory,'run.mat'),'result','-v7.3');
H=result.history; m=result.problem.M; d=result.problem.D;
names=[{'EvaluationID','Stage'},cellstr(compose('x%d',1:d)), ...
    cellstr(compose('f%d',1:m)),cellstr(compose('g%d',1:size(H.G,2))),{'CV'}];
writetable(array2table([H.EvaluationID,H.Stage,H.X,H.F,H.G,H.CV], ...
    'VariableNames',names),fullfile(directory,'true_evaluations.csv'));
writetable(array2table(result.finalF,'VariableNames',cellstr(compose('f%d',1:m))), ...
    fullfile(directory,'final_feasible_nondominated_objectives.csv'));
logs=result.stages; n=numel(logs);
if n>0
    data=zeros(n,13);
    for i=1:n
        s=logs(i);
        data(i,:)=[s.stage,s.FEbefore,s.FEafter,s.usedChoice,s.nextChoice, ...
            s.scores.aggregateRBF,s.scores.aggregateKriging, ...
            s.rbfRank,s.infillSupplementCount];
    end
    names={'Stage','FEbefore','FEafter','UsedObjectiveModel','UsedConstraintModel', ...
        'NextObjectiveModel','NextConstraintModel','R2RBFObjectives','R2RBFConstraint', ...
        'R2KrigingObjectives','R2KrigingConstraint','RBFMatrixRank','InfillSupplementCandidates'};
    writetable(array2table(data,'VariableNames',names),fullfile(directory,'model_selection.csv'));
    rows=zeros(0,10);
    for i=1:n
        s=logs(i);
        for j=1:size(s.truth,2)
            count=size(s.truth,1);
            rows=[rows;repmat(s.stage,count,1),s.newEvaluationIDs, ...
                repmat(j,count,1),s.truth(:,j),s.predictedRBF(:,j), ...
                s.predictedKriging(:,j),repmat(s.scores.rbf(j),count,1), ...
                repmat(s.scores.kriging(j),count,1), ...
                repmat(s.scores.rbfRMSE(j),count,1), ...
                repmat(s.scores.krigingRMSE(j),count,1)]; %#ok<AGROW>
        end
    end
    names={'Stage','EvaluationID','ResponseIndex','Truth','RBFprediction', ...
        'KrigingPrediction','BatchR2RBF','BatchR2Kriging','BatchRMSERBF','BatchRMSEKriging'};
    writetable(array2table(rows,'VariableNames',names),fullfile(directory,'prediction_errors.csv'));
end
summary=struct('status',result.status,'problem',result.problem,'options',result.options, ...
    'FE',result.FE,'runtimeSeconds',result.runtimeSeconds,'metrics',result.metrics, ...
    'finalFeasibleNDCount',size(result.finalF,1), ...
    'nonfiniteIGD',~isfinite(result.metrics.IGD), ...
    'provenance',result.provenance, ...
    'warning','Single-run reconstruction evidence, not a historical or 30-run replication.');
fid=fopen(fullfile(directory,'summary.json'),'w','n','UTF-8');
assert(fid>=0); cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(summary,'PrettyPrint',true));
end
